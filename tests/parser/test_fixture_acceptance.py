# Literal rectangles in F02's PDF streams, not imported from its generator.
PDF_BOXES = ((72, 600, 272, 660), (340, 300, 540, 360))
DISPLAY_SIZES = ((612, 792), (792, 612), (612, 792), (792, 612), (540, 648), (648, 540))
T05_TOLERANCE = 0.005
GRAY_MIN_RATIO = 0.80


def gray_ratio(png):
    width, height, rgb = decode_png_rgb(png)
    gray = sum(all(abs(v - 217) <= 6 for v in rgb[i:i + 3])
               for i in range(0, len(rgb), 3))
    return gray / (width * height)


def crop_pixel_match(full_png, crop_png, golden):
    """Compare actual crop content with the fixed location in the full L0 page.

    PDFium rounds each crop margin separately. Permit one raster pixel around
    the golden origin, but require every RGB byte to match a page slice. This
    checks content placement independently of the crop's reported transform.
    """
    full_w, full_h, full = decode_png_rgb(full_png)
    crop_w, crop_h, crop = decode_png_rgb(crop_png)
    origin_x, origin_y = round(golden[0] * full_w), round(golden[1] * full_h)
    candidates = []
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            x, y = origin_x + dx, origin_y + dy
            if x < 0 or y < 0 or x + crop_w > full_w or y + crop_h > full_h:
                continue
            reference = b''.join(
                full[((y + row) * full_w + x) * 3:((y + row) * full_w + x + crop_w) * 3]
                for row in range(crop_h))
            candidates.append((sum(a != b for a, b in zip(reference, crop)), x, y,
                               hashlib.sha256(reference).hexdigest()))
    mismatch, x, y, reference_hash = min(candidates)
    return {'mismatched_rgb_bytes': mismatch, 'page_pixel_origin': [x, y],
            'reference_rgb_sha256': reference_hash,
            'crop_rgb_sha256': hashlib.sha256(crop).hexdigest()}


def marker_extents(png):
    """Locate connected gray fills in actual L0 pixels, without PDF transforms.

    Same independent flood-fill oracle as the fixture registry's layout test.
    Text holes do not split a filled rectangle's connected background.
    """
    w, h, rgb = decode_png_rgb(png)
    gray = bytearray(all(abs(v - 217) <= 4 for v in rgb[i:i + 3])
                     for i in range(0, len(rgb), 3))
    boxes = []
    for start in range(w * h):
        if not gray[start]:
            continue
        queue = deque([start])
        gray[start] = 0
        x0 = x1 = start % w
        y0 = y1 = start // w
        count = 0
        while queue:
            at = queue.popleft()
            x, y = at % w, at // w
            count += 1
            x0, x1, y0, y1 = min(x0, x), max(x1, x), min(y0, y), max(y1, y)
            for nx, ny in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)):
                if 0 <= nx < w and 0 <= ny < h and gray[ny * w + nx]:
                    gray[ny * w + nx] = 0
                    queue.append(ny * w + nx)
        if count > 200:
            boxes.append((x0 / w, y0 / h, (x1 + 1) / w, (y1 + 1) / h))
    return sorted(boxes)


class FixtureAcceptance(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.started = datetime.now(timezone.utc).isoformat()
        cls.records = []
        # Class cleanup also runs when setUpClass raises; tearDownClass does not.
        # Start failed so a broken registry cannot leave stale passed evidence.
        cls.has_failures = True
        cls.output = os.environ.get('LAB_PDF_FIXTURE_REPORT_DIR')
        if cls.output:
            Path(cls.output).mkdir(parents=True, exist_ok=True)
        cls.addClassCleanup(cls.write_report)
        cls.entries = {entry['id']: entry for entry in rc.load()['fixtures']}
        cls.has_failures = False

    @classmethod
    def write_report(cls):
        if not cls.output:
            return
        report = {
            'format': 'lab-pdf-fixture-evidence-1',
            'commit': subprocess.check_output(['git', 'rev-parse', 'HEAD'], text=True).strip(),
            'working_tree_diff_sha256': hashlib.sha256(subprocess.check_output(['git', 'diff', 'HEAD'])).hexdigest(),
            'schema': 'SourceRegion SPEC 4.1; internal ImportResult',
            'dependencies': {name: version(name) for name in ('pypdf', 'pypdfium2')},
            'pdfium': str(pdfium.version.PDFIUM_INFO),
            'environment': platform.platform(), 'python': platform.python_version(),
            'profile': 'synthetic-registry-pdfium-1; 72/150 DPI; no OCR/providers/DB',
            'seed': None, 'started_at': cls.started,
            'finished_at': datetime.now(timezone.utc).isoformat(),
            'executor': os.environ.get('GITHUB_JOB', 'local coding runner'),
            'ci_run_id': os.environ.get('GITHUB_RUN_ID'),
            'status': 'failed' if cls.has_failures or not cls.records or any(r['status'] == 'failed' for r in cls.records) else 'passed',
            'cases': cls.records,
            'remaining_gates': ['T01 upload/download/version uniqueness',
                                'T02 HTTP content type/status and absence of LLM calls',
                                'T04 artifact reuse/new immutable version',
                                'T05 browser preview/highlight integration',
                                'T06 OCR; T07 batch recovery; DB/artifact persistence',
                                'fixture human signoff and missing registry content'],
        }
        (Path(cls.output) / 'evidence.json').write_text(json.dumps(report, indent=2) + '\n')

    def tearDown(self):
        # Include setup/input-hash failures outside a named case; never emit a
        # passed artifact report merely because its case list is empty/partial.
        result = self._outcome.result
        if any(test is self or getattr(test, 'test_case', None) is self
               for test, _ in result.failures + result.errors):
            type(self).has_failures = True

    def fixture(self, fid):
        entry = self.entries[fid]
        expected = json.loads((rc.ROOT / entry['expected']).read_text())['items']
        for item in entry['items']:
            data = rc.item_bytes(item)
            self.assertEqual(hashlib.sha256(data).hexdigest(), item['sha256'], item['id'])
            yield item, data, expected[item['id']]

    @contextmanager
    def case(self, name, item, test_id, expected):
        record = {'case': name, 'test_id': test_id, 'requirements': ['R01'] if test_id != 'T05' else ['R02', 'R27'],
                  'acceptance_contributors': ['A19'] if test_id == 'T05' else [],
                  'fixture': item['id'], 'fixture_sha256': item['sha256'],
                  'expected_sha256': hashlib.sha256((rc.ROOT / self.entries[item['id'].split('.')[0]]['expected']).read_bytes()).hexdigest(),
                  'steps': 'rebuild pinned fixture; execute named case; compare fixed expected and actual',
                  'expected': expected, 'actual': {}, 'status': 'failed'}
        self.records.append(record)
        with self.subTest(case=name, fixture=item['id']):
            yield record['actual']
            record['status'] = 'passed'

    def asset(self, name, data, index, region=(0, 0, 1, 1), dpi=72):
        asset = render_region(data, index, region, dpi=dpi)
        self.assertEqual(asset.sha256, hashlib.sha256(asset.png).hexdigest())
        if self.output:
            (Path(self.output) / f'{name}.png').write_bytes(asset.png)
        self.records[-1].setdefault('artifacts', []).append(
            {'file': f'{name}.png', 'sha256': asset.sha256, 'size_bytes': len(asset.png)})
        return asset

    def test_f01_hash_counts_and_physical_indices(self):
        for item, data, expected in self.fixture('F01'):
            with self.case('hash/count/physical indices', item, 'T01', expected) as actual:
                inspected = inspect_pdf(data)
                pages = extract_pages(data)
                actual.update(inspect=asdict(inspected), physical_indices=[p.page_index for p in pages])
                self.assertEqual(inspected.outcome, 'accept')
                self.assertEqual(inspected.sha256, item['sha256'])
                self.assertEqual(inspected.page_count, expected['page_count'])
                self.assertEqual([p.page_index for p in pages], list(range(expected['page_count'])))
                # Independently open with PDFium and prove first/last physical page identity.
                with pdfium.PdfDocument(data) as pdf:
                    self.assertEqual(len(pdf), expected['page_count'])
                    for index in sorted({0, expected['page_count'] - 1}):
                        page = pdf[index]
                        try:
                            textpage = page.get_textpage()
                            try:
                                text = textpage.get_text_range()
                            finally:
                                textpage.close()
                        finally:
                            page.close()
                        self.assertIn(f'LAB synthetic fixture F01 - page {index + 1}\r\n', text)
                actual['pdfium_page_count'] = expected['page_count']

    def test_f02_geometry_render_and_negative_controls(self):
        item, data, expected = next(self.fixture('F02'))
        pages = extract_pages(data)
        self.assertEqual(len(pages), len(expected['pages']))
        for exp, page in zip(expected['pages'], pages):
            index = exp['page_index']
            with self.case(f'page-{index}-metadata', item, 'T05', exp) as actual:
                actual.update(asdict(page))
                self.assertEqual(page.page_index, index)
                self.assertEqual(page.page_label, exp['page_label'])
                self.assertEqual(page.rotation, exp['rotate'])
                self.assertEqual(list(page.mediabox), exp['mediabox'])
                self.assertEqual(list(page.cropbox), exp['cropbox'])
                self.assertEqual(page.visible_box, page.cropbox)
                self.assertEqual((page.display_width_pt, page.display_height_pt), DISPLAY_SIZES[index])
                # Physical identity checked with an independent PDF engine, not labels as indices.
                with pdfium.PdfDocument(data) as pdf:
                    p = pdf[index]
                    try:
                        t = p.get_textpage()
                        try:
                            text = t.get_text_range()
                        finally:
                            t.close()
                    finally:
                        p.close()
                for marker in exp['markers']:
                    self.assertIn(marker['text'], text)
                self.assertNotIn(f'MARK-{(index + 1) % len(pages)}-L', text)

            full_pages = {}
            for dpi in (72, 150):
                with self.case(f'page-{index}-full-{dpi}', item, 'T05',
                               {'dimensions_pt': DISPLAY_SIZES[index], 'dpi': dpi}) as actual:
                    asset = self.asset(f'F02-page-{index}-{dpi}', data, index, dpi=dpi)
                    actual.update(sha256=asset.sha256, transform=asset.transform)
                    for got, pt in zip((asset.width_px, asset.height_px), DISPLAY_SIZES[index]):
                        self.assertLessEqual(abs(got - pt * dpi / 72), 1)
                    self.assertEqual(asset.transform['page_size_pt'], DISPLAY_SIZES[index])
                    full_pages[dpi] = asset.png
                    # Anchor every raster scale to fixed geometry. Comparing
                    # crops only to the same renderer's full page can hide a
                    # shared content offset at one DPI.
                    observed = marker_extents(asset.png)
                    actual['observed_marker_bboxes'] = observed
                    golden_boxes = sorted(m['bbox'] for m in exp['markers'])
                    self.assertEqual(len(observed), len(golden_boxes))
                    for got, want in zip(observed, golden_boxes):
                        self.assertLessEqual(max(abs(a - b) for a, b in zip(got, want)), T05_TOLERANCE)

            for marker, box in zip(exp['markers'], PDF_BOXES):
                for dpi in (72, 150):
                    with self.case(f"{marker['text']}-{dpi}", item, 'T05', {'bbox': marker['bbox'], 'pdf_box': box,
                                                              'gray_min_ratio': GRAY_MIN_RATIO, 'dpi': dpi}) as actual:
                        golden = tuple(marker['bbox'])
                        calculated = to_region_space(box, page.visible_box, page.rotation)
                        restored = to_user_space(golden, page.visible_box, page.rotation)
                        actual.update(calculated_bbox=calculated, restored_pdf_box=restored)
                        for got, want in zip(calculated, golden):
                            self.assertLessEqual(abs(got - want), 0.000001)
                        for got, want in zip(restored, box):
                            self.assertLessEqual(abs(got - want), T05_TOLERANCE * max(page.display_width_pt, page.display_height_pt))
                        asset = self.asset(f"{marker['text']}-{dpi}", data, index, golden, dpi=dpi)
                        repeat = render_region(data, index, golden, dpi=dpi)
                        actual.update(sha256=asset.sha256, transform=asset.transform, gray_ratio=gray_ratio(asset.png))
                        self.assertEqual(asset.png, repeat.png)
                        self.assertEqual(asset.transform['region'], golden)
                        self.assertEqual(asset.page_index, index)
                        width, height = DISPLAY_SIZES[index]
                        for got, want in zip((asset.width_px, asset.height_px),
                                             ((golden[2] - golden[0]) * width * dpi / 72, (golden[3] - golden[1]) * height * dpi / 72)):
                            self.assertLessEqual(abs(got - want), 2)
                        self.assertGreater(actual['gray_ratio'], GRAY_MIN_RATIO)
                        actual['full_page_pixel_match'] = crop_pixel_match(full_pages[dpi], asset.png, golden)
                        self.assertEqual(actual['full_page_pixel_match']['mismatched_rgb_bytes'], 0,
                                         'crop pixels must match the golden location in the full page')
                        # Wrong transforms must fail the T05 localization oracle. A wrong crop
                        # may still contain gray pixels, so pixel coverage alone is insufficient.
                        negatives = {'wrong_rotation': to_region_space(box, page.visible_box, (page.rotation + 90) % 360)}
                        if page.cropbox != page.mediabox:
                            negatives['ignored_cropbox'] = to_region_space(box, page.mediabox, page.rotation)
                        actual['negative_controls'] = {}
                        for name, wrong in negatives.items():
                            bad = self.asset(f'{marker["text"]}-{dpi}-{name}', data, index, wrong, dpi=dpi)
                            ratio = gray_ratio(bad.png)
                            actual['negative_controls'][name] = {'bbox': wrong, 'gray_ratio': ratio, 'sha256': bad.sha256}
                            error = max(abs(a - b) for a, b in zip(wrong, golden))
                            actual['negative_controls'][name]['max_coordinate_error'] = error
                            self.assertGreater(error, T05_TOLERANCE, name)

    def test_f05_fixed_outcomes_and_exact_limits(self):
        mapping = {'accept_as_data': 'accept', 'reject_if_over_limit': 'reject'}
        for item, data, expected in self.fixture('F05'):
            with self.case('fixed import outcome', item,
                           'T03' if item['id'] in ('F05.encrypted', 'F05.many_pages') else 'T02', expected) as actual:
                result = inspect_pdf(data)
                actual.update(asdict(result))
                self.assertEqual(result.outcome, mapping.get(expected['outcome'], expected['outcome']))
                self.assertEqual(result.reason, expected['reason'])
                self.assertEqual(result.sha256, item['sha256'])
                self.assertEqual(result.size_bytes, len(data))
                if 'page_count' in expected:
                    self.assertEqual(result.page_count, expected['page_count'])
                if expected['outcome'] == 'flag':
                    self.assertTrue(result.warnings)
                if expected['outcome'] == 'accept_as_data':
                    asset = self.asset('F05-injection-as-data', data, 0)
                    actual['render_sha256'] = asset.sha256
            if item['id'] in ('F05.injection', 'F05.many_pages'):
                count = expected['page_count']
                with self.case('byte limits; page limits when count >1', item, 'T03',
                               {'max_bytes': len(data), 'max_pages': count}) as actual:
                    at = inspect_pdf(data, Limits(max_bytes=len(data), max_pages=count))
                    byte_over = inspect_pdf(data, Limits(max_bytes=len(data) - 1, max_pages=count))
                    actual.update(at=asdict(at), byte_over=asdict(byte_over))
                    self.assertEqual(at.outcome, 'accept')
                    self.assertEqual(byte_over.reason, 'file_too_large')
                    self.assertIsNone(byte_over.page_count)
                    if count > 1:
                        page_over = inspect_pdf(data, Limits(max_bytes=len(data), max_pages=count - 1))
                        actual['page_over'] = asdict(page_over)
                        self.assertEqual(page_over.reason, 'page_limit_exceeded')
                        self.assertEqual(page_over.page_count, count)

    def test_t04_raw_bytes_identity_only(self):
        fixtures = list(self.fixture('F01'))
        first, data, _ = fixtures[0]
        with self.case('same/different raw bytes hash (no persistence)', first, 'T04',
                       {'same_bytes_same_hash': True, 'different_bytes_different_hash': True}) as actual:
            a, b, changed = inspect_pdf(data), inspect_pdf(bytes(bytearray(data))), inspect_pdf(fixtures[1][1])
            actual.update(first=a.sha256, repeat=b.sha256, changed=changed.sha256)
            self.assertEqual(a.sha256, b.sha256)
            self.assertNotEqual(a.sha256, changed.sha256)


