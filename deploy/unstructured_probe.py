"""CI-only probe: really run pinned Unstructured (fast strategy) on a SYNTHETIC PDF and
pass the real element JSON through the #54 normalizer. No model weights, no network
service, no customer data. Prints one JSON report; exits non-zero on any failure.

Run inside a throwaway venv that has ``unstructured==0.27.36`` installed plus the repo's
parser requirements (see .github/workflows/unstructured-probe.yml).
"""
from __future__ import annotations

from datetime import datetime, timezone
import hashlib
import importlib.metadata as md
import json
import sys
import tempfile
import time
from pathlib import Path

from lab_contracts.parse import ModelRevision, PageMapEntry, ParseManifest, ParseRequest, RenderSettings
from lab_parser.normalize import ADAPTER_REVISION, DisplayFrame, UnstructuredParser, UnstructuredProfile

SYNTHETIC_LINES = [
    "Synthetic probe document F01-probe",
    "This page is generated by the repository and contains no customer data.",
    "The quick brown fox jumps over the lazy dog.",
]


def synthetic_pdf() -> bytes:
    """One US-Letter page, Helvetica text, hand-built so no extra dependency is needed."""
    ops = ["BT", "/F1 14 Tf", "72 720 Td", "18 TL"]
    for line in SYNTHETIC_LINES:
        ops.append(f"({line}) Tj T*")
    ops.append("ET")
    stream = "\n".join(ops).encode("ascii")
    objs = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R "
        b"/Resources << /Font << /F1 5 0 R >> >> >>",
        b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out, offsets = bytearray(b"%PDF-1.4\n"), []
    for i, body in enumerate(objs, 1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % i + body + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1)
    for off in offsets:
        out += b"%010d 00000 n \n" % off
    out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objs) + 1, xref)
    return bytes(out)


def main() -> int:
    from unstructured.partition.pdf import partition_pdf
    from unstructured.staging.base import elements_to_dicts

    version = md.version("unstructured")
    data = synthetic_pdf()
    sha = hashlib.sha256(data).hexdigest()
    started = datetime.now(timezone.utc)
    t0 = time.monotonic()
    with tempfile.TemporaryDirectory() as d:
        path = Path(d, "synthetic_f01_probe.pdf")
        path.write_bytes(data)
        elements = partition_pdf(filename=str(path), strategy="fast")
    wall = time.monotonic() - t0
    raw = json.dumps(elements_to_dicts(elements), sort_keys=True).encode("utf-8")
    finished = datetime.now(timezone.utc)

    report = {
        "synthetic": True,
        "python": sys.version.split()[0],
        "unstructured": version,
        "pdf_sha256": sha,
        "wall_seconds": round(wall, 3),
        "element_count": len(elements),
        "raw_sha256": hashlib.sha256(raw).hexdigest(),
        "versions": {n: md.version(n) for n in ("pdfminer.six", "pypdf", "pydantic") if _has(n)},
    }
    if version != "0.27.36":
        report["result"] = "version_mismatch"
        print(json.dumps(report, indent=2))
        return 1

    request = ParseRequest(document_artifact_ref="sha256:" + sha, page_indices=[0],
                           profile_revision="unstructured-oss-fast",
                           budget_ref="b-probe", operation_id="op-probe")
    manifest = ParseManifest(
        parser_name="unstructured", package_or_service_version=version,
        adapter_revision=ADAPTER_REVISION, output_schema="unstructured.elements-0.27.36",
        model_revisions=[ModelRevision(name="core", revision=version, checksum=None)],
        requested_profile="unstructured-oss-fast", effective_profile="unstructured-oss-fast",
        fallback_reason=None, ocr_languages=["en"], page_selection=[0],
        page_index_map=[PageMapEntry(parser_page=1, page_index=0)],
        render_settings=RenderSettings(dpi=150, max_megapixels=16.0), postprocess_flags=[],
        endpoint_deployment_id=None, started_at=started, finished_at=finished,
        cost_usd=0.0, warnings=[], reproducible=True)
    batch = UnstructuredParser().normalize(
        raw, request, manifest, UnstructuredProfile(strategy="fast"),
        document_id="doc-synthetic-f01-probe", document_sha256=sha,
        frames={0: DisplayFrame(coordinate_frame="rotated_cropbox_top_left", width=612.0,
                                height=792.0, transform_ref="probe-p0")},
        document_page_count=1)
    report["quarantine_reason"] = batch.quarantine_reason
    report["evidence_units"] = len(batch.evidence)
    report["observations"] = len(batch.observations)
    report["evidence_text"] = [e.raw_content for e in batch.evidence][:10]
    ok = batch.quarantine_reason is None and len(batch.evidence) > 0
    # Second, stricter leg: the same PDF through the isolation-child runner, with frames
    # derived from real page geometry (no hand-set frame).
    from lab_parser.unstructured_runner import run_unstructured_fast
    t1 = time.monotonic()
    isolated = run_unstructured_fast(data, python=sys.executable, document_id="doc-synthetic-f01-probe",
                                     budget_ref="b-probe", operation_id="op-probe-isolated")
    report["isolated"] = {
        "wall_seconds": round(time.monotonic() - t1, 3),
        "quarantine_reason": isolated.quarantine_reason,
        "evidence_units": len(isolated.evidence),
        "evidence_text": [e.raw_content for e in isolated.evidence][:10],
        "bbox": [list(e.regions[0].bbox) for e in isolated.evidence][:10],
        "frame_source": "inspect_geometry",
    }
    ok = ok and isolated.quarantine_reason is None and len(isolated.evidence) > 0
    report["result"] = "pass" if ok else "fail"
    print(json.dumps(report, indent=2))
    return 0 if ok else 1


def _has(name: str) -> bool:
    try:
        md.version(name)
        return True
    except md.PackageNotFoundError:
        return False


if __name__ == "__main__":
    raise SystemExit(main())
